const paths = (productId: string, owner = user) => [0, 1].map(i => `products/${owner}/${productId}-${i}.jpg`);
async function upload(productId: string, owner = user) {
  for (const path of paths(productId, owner)) {
    await db.query(`INSERT INTO storage.objects(bucket_id,name,metadata) VALUES ('product-images',$1,'{"mimetype":"image/jpeg","size":200}')`, [path]);
  }
}
async function publish(productId: string, details = product, images = paths(productId)) {
  return db.query<{ result: { id: string; slug: string; image_count: number } }>(
    'SELECT public.publish_web_product($1::uuid, $2::jsonb, $3::text[]) AS result',
    [productId, JSON.stringify(details), images]);
}
async function count(productId: string, table = 'products') {
  const column = table === 'products' ? 'id' : 'product_id';
  return (await db.query<{ count: number }>(`SELECT count(*)::int AS count FROM public.${table} WHERE ${column}=$1`, [productId])).rows[0].count;
}

