test('cannot reuse someone else\'s product ID or storage path', async () => {
  const productId = id(); await upload(productId); await publish(productId);
  await db.exec(`SET request.jwt.claim.sub = '${otherUser}';`);
  try {
    await assert.rejects(publish(productId), /Invalid image ownership/);
    await upload(productId, otherUser);
    await assert.rejects(publish(productId, product, paths(productId, otherUser)), /Product ID unavailable|duplicate key/);
  } finally { await db.exec(`SET request.jwt.claim.sub = '${user}';`); }
  assert.equal(await count(productId), 1);
});
